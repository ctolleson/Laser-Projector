def line_width(text):
    """Width of a rendered string, in glyph units."""
    if not text:
        return 0.0
    w = sum(SPACE if ch == ' ' else ADVANCE for ch in text)
    return w - (SPACE if text[-1] == ' ' else ADVANCE - WIDTH)


def strokes(text, missing='?'):
    """Strokes for `text`, laid out left to right from the origin at baseline."""
    out, pen = [], 0.0
    for ch in text.upper():
        if ch == ' ':
            pen += SPACE
            continue
        g = GLYPHS.get(ch) or GLYPHS.get(missing) or []
        for s in g:
            out.append([(x + pen, y) for x, y in s])
        pen += ADVANCE
    return out

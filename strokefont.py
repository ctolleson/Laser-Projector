"""
strokefont.py -- a single-stroke (Hershey-style) vector font for laser text.

A laser cannot use a normal TrueType font: those glyphs are filled *outlines*,
so tracing one draws a hollow, doubled letter. Laser text needs centreline
strokes -- one pass down the middle of each stem.

Glyphs live on a 4 x 7 box: x in 0..4, baseline y=0, cap height y=7.
Each glyph is a list of strokes; each stroke is a polyline the beam draws in
one lit pass. Fewer strokes per glyph = fewer blanked jumps = cheaper frames.
"""
import math

WIDTH, CAP = 4.0, 7.0
ADVANCE = 5.0          # glyph box + side bearing
SPACE = 3.0


def _arc(cx, cy, rx, ry, a0, a1, n=7):
    """Points along an ellipse arc, a0 -> a1 in degrees (sign sets direction)."""
    return [(cx + rx * math.cos(math.radians(a)),
             cy + ry * math.sin(math.radians(a)))
            for a in (a0 + (a1 - a0) * i / n for i in range(n + 1))]


